import path from 'path';
import fs from 'fs/promises';
import { execFile } from 'child_process';

export async function fileExists(path: string) {
  try {
    await fs.stat(path);
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') {
      return false;
    } else {
      throw error;
    }
  }
}

function run(command: string, args: string[], cwd: string): Promise<void> {
  return new Promise((resolve, reject) => {
    execFile(command, args, { cwd }, (err) => {
      if (err) {
        reject(err);
      } else {
        resolve();
      }
    });
  });
}

export async function initGitRepo(directoryPath: string, packageManager: string) {
  const packageManagerExecutables = {
    deno: 'deno',
    npm: 'npm',
    pnpm: 'pnpm',
    yarn: 'yarn',
  } as const;
  const packageManagerExecutable = packageManagerExecutables[packageManager as keyof typeof packageManagerExecutables];

  if (!packageManagerExecutable) {
    throw new Error(`Unsupported package manager: ${packageManager}`);
  }

  await run('git', ['init'], directoryPath);
  const packageManagerArgs = packageManager === 'deno' ? ['cache', '--lock=deno.lock', '--lock-write', 'deps.ts'] : ['install'];

  if (process.platform === 'win32' && packageManager !== 'deno') {
    await run('cmd.exe', ['/d', '/s', '/c', packageManagerExecutable, ...packageManagerArgs], directoryPath);
  } else {
    await run(packageManagerExecutable, packageManagerArgs, directoryPath);
  }
  await run('git', ['add', '.'], directoryPath);
  await run('git', ['commit', '-m', 'init commit generated by starter.dev CLI'], directoryPath);
}

export async function removeLockFileIfExists(fileName: string, directoryPath: string): Promise<boolean> {
  let removed: boolean;
  try {
    await fs.unlink(path.join(directoryPath, fileName));
    removed = true;
  } catch (err) {
    removed = false;
  }
  return removed;
}

export async function overrideAngularJsonIfExists(directoryPath: string, kitName: string, newProjectName: string): Promise<boolean> {
  let done: boolean;
  const angularJsonPath = path.join(directoryPath, 'angular.json');
  try {
    const content = await fs.readFile(angularJsonPath, 'utf8');
    const newContent = content.replace(new RegExp(kitName, 'g'), newProjectName);
    await fs.writeFile(angularJsonPath, newContent);
    done = true;
  } catch (err) {
    done = false;
  }
  return done;
}
